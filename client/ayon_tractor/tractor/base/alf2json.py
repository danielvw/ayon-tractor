class AlfJobParser(object):
    '''Read an alfred-style job definition from the specified file,
       and parse it as "job data" (but not executable Tcl).
       Build an intermediate Python hierarchy of dicts and lists
       representing the Task/Cmd structure, then serialize that
       as JSON in the slightly awkward form expected by Tractor2.
       Parsing line-by-line to help minimize intermediate copies
       of large job scripts.
    '''

    def __init__(self, options):
        # Inbound options are expected to be an object similar to those
        # created by the optparse or argparse modules. But really it's
        # just an object carrying attributes that can be queried.

        self.options = options

        #  "2.0" is Tractor2 compat, "3.0" is a simpler layout and escaping
        self.options.jsonAPI = getattr(options, "jobspec", "2.0")

        self.options.jobowner    = getattr(options, "user", getpass.getuser())
        self.options.jobfile     = getattr(options, "jobfile", "<scripted>")
        self.options.loglevel    = getattr(options, "loglevel", 1)
        self.options.priority    = getattr(options, "priority", 1.0)
        self.options.paused      = getattr(options, "paused", 0)
        self.options.cleanupSvc  = getattr(options, "remoteclean", "PixarRender")
        self.options.jobcwd      = getattr(options, "jobcwd", os.getcwd().replace("\\", "/"))
        self.options.spooltime   = getattr(options, "spooltime", time.time())
        self.options.jsonformat  = getattr(options, "jsonformat", (None, (',', ':')))
        self.options.spoolerHost = getattr(options, "hname", '')
        self.options.expandctx   = getattr(options, "expandctx", None)
        self.options.envkey      = getattr(options, "envkey", [])
        self.options.strict      = getattr(options, "strict", False)

        if not self.options.spoolerHost:
            self.options.spoolerHost = socket.gethostname().split('.')[0]

        if self.options.jobfile and list == type(self.options.jobfile):
            self.options.jobfile = self.options.jobfile[0] + "..."

        # parser state / tracking
        self.ntid = 0
        self.ncid = 0
        self.context = None
        self.cmdScope = 'C'  # of C, D, P
        self.taskStack = []
        self.jobsrc = None
        self.linenum = 0
        self.linebuf = StringIO() # reused line buffer


    def xlateAlfToJSON(self, jobsrc):
        '''Parse the inbound lines to construct a nested hierarchy
           of python dicts representing the job's task tree.
           Then serialize the python data to outbound JSON.
        '''

        ctx = "Job" if not self.options.expandctx else "Expand"

        self.jobsrc = jobsrc

        theJob = self.initJobStatement()  # skeleton job dict

        theJob = self.handleJobStatements(ctx, theJob)

        # done reading file!
        theJob = self.finalizeJobForJSON(theJob)

        return self.generateJSON(theJob)


    def handleJobStatements(self, ctx, theJob, curTask=None):
        '''Evaluate job script objects and their parameters,
           create Python objects of each type in a nested tree.'''

        # NOTE: theJob is initialized in initJobStatement
        self.CTX(ctx)
        while True:
            self.dbg("MAINLOOP")

            # Read next line from the job script, buffer it.
            if not self.refillLineBuffer():
                self.dbg("[[[ EOF - END OF JOB SCRIPT ]]]")
                break   # reached end of input (EOF)

            thing = self.findOneTclToken()
            self.dbg("new thing:", repr(thing))
            if not thing:
                continue  # odd empty buffer, get another

            elif thing == "_BlockEnd_":
                # This line begins with a close-brace, marking the end of
                # a subtask or cmd block. That block parameter value is now
                # complete, so tidy the state and then continue scanning
                # for additional Task parameters.
                curTask = self.handleBlockEnd(curTask)

            elif "Instance" == thing:
                # non-tree ref to a blocking task
                self.handleInstanceStatement()
                # now no active task still capturing params
                curTask = None

            elif not self.contextOK(thing, theJob):
                raise TrAlfParseError("unexpected '%s' in %s context, line %d" % (thing,self.CTX(),self.linenum))

            elif "Job" == thing:
                # Update the supplied Job parameters.
                # The basic top-level Job dict was created above 
                # by initJobStatement().
                curTask = self.addTaskParams(theJob)

            elif "Task" == thing:
                curTask = self.handleTaskStatement()

            elif thing in ("RemoteCmd", "Cmd"):
                # expect:
                #   RemoteCmd -service sss -x y {echo "the args" today}
                #         Cmd -x y {run this on submitting host}

                # collect cmd parameters, then add (one) new cmd to task
                self.handleCmdStatement(thing, curTask, theJob)

            elif thing == "Assign":
                self.handleAssignStatement()

            else:
                raise TrAlfParseError("unrecognized job script statement/node type '%s' line %d" % (thing, self.linenum))

        return theJob


    def initJobStatement(self):
        # Create the Job top level.
        # Jobs are just specialized Tasks with extra attributes.
        #
        # NOTE: dict items defined here will be sent in the 
        #       outbound JSON if they differ from the defaults.

        t = int(self.options.spooltime)

        job = {
            "jid": 0,  # real jid set by tractor-engine
            "owner":     self.options.jobowner,
            "spoolhost": self.options.spoolerHost,
            "spooltime": t,
            "spooldate": time.strftime("%Y-%m-%d %H:%M:%S %Z", time.localtime(t)),
            "spoolfile": self.options.jobfile,
            "spoolcwd":  self.options.jobcwd,
            "tid": 0,  # by convention for the job "task"
            "commands": [],
            "subtasks": [],
        }
        optional = {
            ("title", "jtitle"),
            "paused",
            "priority",
            "crews",
            "projects",
            "envkey",
            ("afterjids", "afterjid"),
            "aftertime",
            "maxactive",
            "tags",
            "tier",
            "comment",
            "metadata",
        }
        self.chkOptionals(optional, self.options, job)

        # return the job dict
        return job


    def chkOptionals(self, optional, inopts, job):
        for name in optional:
            if tuple == type(name):
                oname = name[1]
                name = name[0]
            else:
                oname = name
            
            x = getattr(inopts, oname, None)
            if x != None:
                dflt = s_defaultParams["Job"][name]
                kind = type(dflt)
                try:
                    if name == "aftertime":
                        x = self.chkDelayTime(x)
                    elif kind == int:
                        x = int(x)
                    elif kind == list:
                        x = self.chkIsList(x)
                    else:
                        x = str(x)
                        
                    if x != dflt:
                        job[name] = x
                except:
                    print("Error: cannot set job option '%s' to '%s'" % (name,x), file=sys.stderr)


    def handleTaskStatement(self):
        # expect:
        #
        #  Task {some title} [options] -subtasks {...} -cmds {...}
        #
        # Note the missing implicit "-title" preceeding title!
        # So we'll add an explicit "-title" keyword, so that
        # regular key-value processing can proceed below.

        # Increment the global task id/count.
        # Then negate the tid and save that in the dict
        # as an indicator that the task has been created
        # but not yet attached to the job graph.
        tid = self.ntid + 1
        self.ntid = tid

        curTask = {  # a new Task parameter dictionary
            "title": "",
            "commands": [],
            "subtasks": [],
        }
        curTask['tid'] = -tid
        self.dbg("created <<Task>>", curTask['tid'])

        return self.addTaskParams(curTask)


    def mkNewCmd(self):
        '''Create a new dictionary of (Remote)Cmd parameters'''
        self.ncid += 1  # incr global cmd id/count
        cmd = {
            "cid": self.ncid,
            "argv": [],
            "type": '',
        }
        self.dbg("created CID(%d)" % self.ncid)
        return cmd


    def handleCmdStatement(self, mode, curTask, curJob):
        '''Populate a new cmd dict with scanned parameters.'''
        #
        # Must handle ancient RemoteCmd anachronism re: argv,
        # namely that the argv string can occur anywhere
        # among params, but has no "-argv" keyword!
        #
        # like: RemoteCmd -service "linux_2XL" -atmost 1 "sleep 4"
        #   or: RemoteCmd {my command xyz} -service linux_2XL
        #
        implicit = "argv"
        cmdTag = ''

        cmd = self.mkNewCmd()

        while True:
            key, value = self.gatherNextParamPair(implicit)
            if not key:
                # reached EOL, cmd parameters complete
                break
            elif key == "_BlockEnd_":
                # Reached end of parameters, and also this
                # command was the last one in the -cmds block,
                # push that back on the read stream for the 
                # task-level scan to find it.
                self.rewind1("cmdblk")
                break
            elif not value:
                # skip, param has default value
                continue
            else:
                # got a valid RemoteCmd key,
                # and the value is different than the default
                self.dbg("  Adding", key, '=', value, "to cmd cid:", cmd['cid'])
                cmd[key] = value

                if implicit == key:
                    # found a value for the implicit key, so return
                    # to requiring proper key-value pairs only
                    implicit = None

        # reached end of cmd params,
        # tidy various details
        if cmd['argv']:
            cmdTag = self.normalizeExeFilename(cmd)
        else:
            raise TrAlfParseError("missing launch executable in -cmds, line %d" % self.linenum)

        # The command "type" defines where and when it runs over the course
        # of the job. Where is either local or remote (workstation or farm)
        # and when is either during the main body of the job or after
        # processing is complete (at both task and job levels). The "when"
        # is usually determined by the parameter scope in which the cmd is
        # found, -cmds {} or -cleanup {} blocks, plus some other case. 
        # See addTaskParameters() where the scope is known and stored into
        # self.cmdScope.
        #
        # Command type & scope, such as RC or RD or LPD or RCX
        #  First letter:
        #    L or R  - local or remote command (Cmd vs RemoteCmd)
        #  Second letter:
        #    C - regular command
        #    D - a cleanup or "deleting" command
        #    P - job postscript, runs at job end
        #  Third letter:
        #    X - after C, cmd will "expand" to other tasks
        #    D - after P, runs when the job is Done
        #    E - after P, runs when the job had Errors
        #
        # Local commands must run on the submitting workstation
        # (an Alfred concept that is increasingly outdated).
        # If needed, the engine creates local commands by setting
        # the command service key to the workstation hostname,
        # as seen by the engine host - similar to:
        #        if mode == "Cmd" and not cmd.get('service'):
        #            cmd["service"] = self.spoolerHost
        #
        # Also, to support really old RfM format jobs, if the service
        # prefix is "local:" then the command is coerced into a local
        # cmd if it isn't already, and the service key is dropped but
        # the suffix is retained in the tags for limit counting.

        cmdModeBase = {
            "Cmd":       'L',  # Local
            "RemoteCmd": 'R',  # Remote
        }
        cmdType = cmdModeBase[mode]

        svc = cmd.get('service')
        if svc and svc.startswith("local:"):
            cmdType = 'L'
            cmdTag = svc[6:] + ' ' + cmdTag
            del cmd['service']
            svc = None

        if cmdType == 'L' and self.cmdScope == 'D':
            svc = self.options.cleanupSvc
            if svc:
                cmdType = 'R'
                cmd['service'] = svc
            
        if mode=="RemoteCmd" and not svc and not self.options.expandctx and \
            not cmd.get('refersto') and not curJob.get('service'):
            # This exception is spurious when the Job-level -service option
            # is given after all cmds since this parser is line-by-line and
            # hasn't see the (correct) job-level service yet. Usually it is
            # emitted at the top of the alfscript by job authoring toosl.
            raise TrAlfParseError("Job syntax error, no RemoteCmd -service/-refersto given or inherited, line %d" % self.linenum)

        cmdType += self.cmdScope  # like RC or RD or RP

        if cmd.get("expand", 0):
            cmdType += 'X'

        when = cmd.get("when",'')
        if when:
            del cmd["when"]  # don't emit in JSON
            if self.cmdScope != 'P':  # postscripts only
                raise TrAlfParseError("Command -when is only valid inside the Job -postscript block")
            else:
                if when == "done":
                    cmdType += 'D'   # like RPD
                elif when == "error":
                    cmdType += 'E'   # like RPE
                else:
                    raise TrAlfParseError("Unknown command -when value: %s" % when)

        cmd["type"] = cmdType

        # now tags and argv/cmdTag are both in hand, so finalize limit tags
        cmd["tags"] = self.reformatLimitTags(cmd.get("tags",'') + ' ' + cmdTag)

        self.updateSlotCounts(cmd)
        if "maxslots" in cmd and 0 < cmd["maxslots"]:
            cmd["maxhosts"] = 1  # cmd only, 2.0 compat

        #
        # Now the Cmd is complete!
        # Attach it to its enclosing task.
        #
        self.addCmdToTask(cmd, curTask)


    def addCmdToTask(self, cmd, curTask):
        self.dbg("ADDING cmd", cmd['cid'], "to task", curTask['tid'], "nc:", len(curTask['commands']))
        curTask['commands'].append(cmd)
        if 'cids' not in curTask:
            curTask['cids'] = [cmd['cid']]
        else:
            curTask['cids'].append(cmd['cid'])


    def handleInstanceStatement(self):
        # A simple reference some other task as a blocking
        # requirement in a not-strictly-tree way. Can appear 
        # in a subtask group, like "Task". These references
        # (to the TITLE(!) of the other task) are stored in
        # a separate "antecedents" list on the blocked
        # (parent/successor) task.

        if self.CTX() != "Task" or not self.taskStack:
            raise TrAlfParseError("'Instance' only allowed in subtask context, line %d" % self.linenum)

        taskref = self.findOneTclToken()

        pt = self.taskStack[-1] # parent on stack
        if "ants" not in pt:
            pt["ants"] = []

        pt["ants"].append(taskref)

        self.dbg("ADDING Instance ref <", taskref, "> to task", pt['tid'])


    def handleAssignStatement(self):
        '''The Assign operator is unsupported here,
           but consume the parameters.
        '''
        self.dbg("Assign loop ...")
        while True:
            key = self.findOneTclToken()
            if not key or key == "_BlockEnd_":
                # End of parsing inside -init block.
                break
            value = self.findOneTclToken()
            self.dbg("(skip) Assign", key, value)

    def handleBlockEnd(self, curTask):
        # found _BlockEnd_ on a new line or inline after cmds or subtasks
        if "Cmd" == self.CTX():
            # This was the final Cmd tastement in the task's -cmds block,
            # so resume finding any addition task-level parameters ...
            self.dbg("end CMD block in tid:", curTask['tid'] if curTask else "<<none>>")
            self.CTX("Task")

        elif "Task" == self.CTX():
            if curTask:
                # Stow the final subtask in the block if no eol prior.
                self.chkAttachTaskToParent(curTask)

            # then return the param parsing scope to the parent
            curTask = self.taskStack.pop()
            self.dbg("POP stk =", len(self.taskStack), "task now:", curTask['tid'])
            self.dbg("  after block, task =", curTask['tid'])

        elif "Assign" == self.CTX():
            self.dbg("end INIT/Assign block")
            self.CTX("Job")

        else:
            raise TrAlfParseError('reached statement-block end in unexpected %s context, line %d' % (self.CTX(), self.linenum))

        if 0 == curTask['tid']:
            self.CTX("Job")

        # Can be more params for the enclosing Task after the block
        return self.addTaskParams(curTask)


    ## ===== ##


    def CTX(self, newctx=None):
        '''query or set the parsing context'''
        x = self.context
        if newctx:
            self.context = newctx
        return x

    def log(self, *a, **k):
        print(*a, file=sys.stderr)

    def dbg(self, *a, **k):
        if self.options.loglevel >= 5:
            ctxs = "(%s)," % self.context
            print("line %d %-5s  " % (self.linenum, ctxs), *a, file=sys.stderr)

    def trace(self, *a, **k):
        if self.options.loglevel >= 11:
            self.dbg(*a)

    def contextOK(self, pkey, jobdict):
        '''Confirm that the job directive 'pkey' is allowed
           within the current parsing context.'''

        if self.CTX() == "Expand":
            # Obscure compatibility issue:  alfred allowed expand output to
            # benignly begin with "Job" where the job node itself was ignored.
            # We try to emulate this weird aberration since it is still used
            # at a venerable studio. Let's call it: strongly deprecated.
            if pkey == "Job":
                self.CTX(pkey)
            elif pkey == "Task":
                self.CTX(pkey)
                self.taskStack = [jobdict]

        return pkey == self.CTX() or (
            self.CTX() == "Cmd" and pkey in (
                    "RemoteCmd",
                    "Cmd",
                )
            )


    def normalizeExeFilename(self, cmd):
        # Canonicalize path separators in argv[0] to always be
        # fwd slash '/' which works equally well on all platforms.
        #
        # Also Tractor assumes that the "base executable name"
        # will always be included as a limit tag, so extract that
        # while the pathlib machinery is spun up.
        a0 = cmd['argv'][0]

        # in python3 we could use the somewhat overwraught pathlib,
        # (but not portable to 2.x), for example:
        # if '\\' in a0:
        #   a0 = pathlib.PureWindowsPath(a0)
        #   cmd['argv'][0] = a0.as_posix()  # canonical with /
        #   cmdstem = a0.stem
        # else:
        #     cmdstem = pathlib.PurePosixPath(a0).stem

        # py2 approximation ...
        if '\\' in a0:
            a0 = a0.replace('\\', '/')
            cmd['argv'][0] = a0 # now tractor normalized
        b = os.path.basename(a0)
        cmdstem = os.path.splitext(b)[0]

        return cmdstem


    def chkIsList(self, txt):
        if not txt:
            return []
        elif list != type(txt):
            return self.tclListToPythonList(str(txt))
        else:
            return txt

    def chkDelayTime(self, timestr):
        ''' expect: float epoch secs, or "10/29 15:45"
            return: epoch secs
        '''
        if not timestr:
            return 0  # job can run now
        try:
            t = float(timestr)
            return t  # assumed secs since epoch like `date +%s`
        except:
            timestr = str(timestr)
            # save current time, and year
            now = time.time()  # current epoch secs
            nowtm = time.localtime(now) # default
            t = None
            # try several patterns, take the first that matches
            for pat in ("%m/%d %H:%M", "%m/%d/%y %H:%M",
                        "%m %d %H:%M", "%Y-%m-%d %H:%M"):
                try:
                    t = time.strptime(timestr, pat)
                    t = list(t)  # now mutable
                    break # success! parsed into struct_time
                except:
                    pass

            # Note: if we end up needing to modify the result
            # struct_time is an immutable tuple, make an editable list

            if not t:
                # try a parse with just hr:min 
                # if that succeeds, fill in the yr, mo, day from "now"
                try:
                    t = time.strptime(timestr, "%H:%M")
                    # success (no exception)
                    t = list(t)  # now mutable
                    t[0] = nowtm.tm_year
                    t[1] = nowtm.tm_mon
                    t[2] = nowtm.tm_mday
                    epsecs = time.mktime(t)
                    if epsecs < now - (60 * 60):
                        # given time would be more than 1hr ago
                        # so assume tomorrow
                        t[2] = nowtm.tm_mday + 1
                except:
                    print("Warning: aftertime can't be parsed '%s'" % timestr, file=sys.stderr)
                    return 0  # job can run now

            if t[0] == 1900:
                # python default 1900 when no yr specified (diff from libc)
                # so add the current year
                t = list(t)  # now mutable
                t[0] = nowtm.tm_year  # this year
                epsecs = time.mktime(t)
                if epsecs < now - (60 * 60 * 24 * 31 * 6):
                    # using this year the date would be more than 6mo
                    # in the past, so instead assume next year
                    t[0] = nowtm.tm_year + 1
                    epsecs = time.mktime(t)

            epsecs = time.mktime(t) # epoch secs

            return 0 if now == epsecs else epsecs


    def updateSlotCounts(self, node):
        '''Old alfscript syntax is -atleast -atmost
           but we prefer the more descriptive minslots maxslots.
           Port the old fmt to the new if it was used.
        '''
        if "atleast" in node:
            if "minslots" not in node:
                node["minslots"] = node["atleast"]
            del node["atleast"]
        if "atmost" in node:
            if "maxslots" not in node:
                node["maxslots"] = node["atmost"]
            del node["atmost"]

        if "samehost" in node:
            # Tractor(3) doesn't support old netrender style
            # allocation of multiple HOSTS to a single Cmd.
            # (Some other netrender thing may come along.)
            # So "samehost" is implicit in all Cmd/RemoteCmd.
            del node["samehost"]


    def reformatLimitTags(self, tagstr):
        '''Convert tcl list of limit tags to a simplified
           blank delimited list of names in a string.'''
        # The complete list of limit tags to tally will be:
        #   o  the app name (command executable), e.g. "txmake"
        #   o  plus the "-tags" list from the Cmd args
        #   o  plus the "-tags" list from the Job args
        #   o  plus the service keys that matched the blade
        #
        # The engine will add the cmdname and svckeys if
        # they are not already present in the cmd -tags list,
        # so that each limit tag is only tallied once. 
        # Make sure that the tag list for this current
        # context internally only has unique values.
        #
        # Job scripts may specify a list of tags using Tcl list notation:
        #     Cmd -tags {{houdiniengine_limit} {mpcpython}} ...
        #
        # The outbound json tag "lists" are not actual json/python lists,
        # due to dynamic composition requirements with other tag lists
        # (listed above). Instead they are sent as blank-delimited
        # words in a simple string. Tag names containing spaces are
        # not supported.

        # Use a python 'set' to uniquify the tag names,
        # then convert that back to a blank-delimited string.
        taglist = self.tclListToPythonList(tagstr)
        uniqueTags = set(taglist)
        return  ' '.join(uniqueTags).lower()


    def reformatDirmaps(self, tclMaps):
        '''Generate python list-of-lists from the tcl dirmap lists.
           Like: Job -dirmaps { {{from} {to} {zone}} {"from" to zone} }
        '''
        # Note: the job template type for dirmaps is 'str' so that the
        # whole complex nested block is read at once, but the outbound
        # result is expected to be a true json list of [list mappings],
        # so this subparsing step is also a type conversion.
        # First step is list of the separate maps:
        #   like { {a "b1 b2" c} {d e f} } -> ["a \"b1 b2\" c", "d e f"]
        # then subparse to get final list of lists
        #    -> [["a", "b1 b2", "c"], ["d", "e", "f"]]

        try:
            pyMaps = self.tclListToPythonList(tclMaps)
            if pyMaps:
                # then subparse the tcl list in each mapping
                stmp = StringIO()  # a reusable StringIO
                pyMaps = [self.tclListToPythonList(x, stmp) for x in pyMaps]
        except:
            raise TrAlfParseError("malformed directory mapping: '%s'" % tclMaps)
                    
        self.dbg("dirmaps:", pyMaps)
        if not pyMaps:
            pyMaps = ''  # match the template so it is skipped
        return pyMaps


    def handleOldWhenCmd(self, when, cmdstr, jobDict):
        '''Deal with -whendone and -whenerror options, which were an older
           approach to postscripts - just raw shell cmdlines. Convert to
           Cmds like those from the postscript block (eg. only attached to
           the commands list at the job level. In Alfred these were always
           local "shell-out" cmds, running on the artist's workstation via
           the local dispatcher. Tractor can do the same thing if (every)
           artist has a blade agent running on their workstation. OR if
           these cmdlines can be run anywhere on the farm then they can be
           RemoteCmds - but a service key is required to target the correct
           blades, see the tractor-spool --remotecleankey=ssss option.
        '''

        # Note: This is a highly simplified version of handleCmdStatement
        # for this special case. See that method for details and rationale.
        cmd = self.mkNewCmd()
        svc = self.options.cleanupSvc  # was a "cleaning service" given?
        if svc and svc != "local":
            cmd['service'] = svc
            cmd["type"] = 'R' # RemoteCmd
        else:
            cmd["type"] = 'L' # local Cmd

        # whendone/error are always postscript 'P' commands
        cmd["type"] += 'PE' if when=="whenerror" else 'PD'
        cmd["tags"] = when
        cmd["argv"] = ["TractorBuiltIn", "System", cmdstr] # shell out
        self.addCmdToTask(cmd, jobDict)


    def finalizeJobForJSON(self, jobDict):
        '''Check final job validity and wrap up some
           job format compatibility items.
        '''

        stlen = len(self.taskStack)

        if self.options.expandctx and stlen == 1 and \
            self.taskStack[0]["tid"] == 0:
                # job may have been pushed artificially for expand tasks
                self.taskStack = []
                stlen = 0

        if 0 != stlen:
            # still open subtask blocks
            raise TrAlfParseError("premature end of job file at line %d (task depth %d)" % (self.linenum,stlen))
        elif self.ncid < 1:
            # job with no cmds is weird/pointless but technically legal
            print("Warning: NO commands to launch specified in job", file=sys.stderr)

        self.CTX("JobEnd")

        self.updateSlotCounts(jobDict)

        # handle old compatibility translation:
        # prefer explicit "-priority N" to pbias, and remove pbias so it
        # isn't emitted. Since T2 pbias is no longer a "bias" but just
        # a priority value.
        pbias = None if "pbias" not in jobDict else jobDict.pop('pbias')
        if "priority" not in jobDict:
            jobDict["priority"] = 1.0 if pbias==None else pbias

        # Apply command-line option overrides to various values that 
        # may or may not have been set in the job script itself.
        ufile = getattr(self.options, "userfile", None)
        if ufile:
            # name of the file submitted by the user, on their client host,
            # rather than the name of tmp file on the engine host
            jobDict['spoolfile'] = ufile

        # And finally, renest the top-level items if necessary.
        if self.options.expandctx:
            # expand scripts only specify new tasks (not jobs)
            jobDict = jobDict.pop('subtasks')

        elif self.options.jsonAPI == "2.0":
            # re-nest topmost level as expected for 2.0
            jobDict = {
                "data": jobDict,
                "children": jobDict.pop('subtasks'),
            }

        return jobDict


    def generateJSON(self, jobDict):
        '''Translate the job python dict hierarchy to JSON.'''

        jobJSON = json.dumps(jobDict, indent=self.options.jsonformat[0],
                                      separators=self.options.jsonformat[1])

        del jobDict  # discard potentially large python dict repr

        self.dbg("parse complete!\n\n======\n")

        if not jobJSON:
            jobJSON = "{}"

        if self.options.jsonAPI == "2.0" and jobJSON[0]=='{':
            # Add expected 2.0 job "header" (specific opening dict lines),
            # basically replacing the opening brace ... and in python
            # that means generating an entire 2nd copy of the potentially
            # huge json job text that was just created.
            header = '{ "TractorJob": "2.0",\n' + \
                     '  "generator": "Tractor3 alf2json.py",\n'
            jobJSON = header + jobJSON[1:]  # replace opening json brace with header

        # done!
        return jobJSON


