    def rewind1(self, msg):
        '''Back up one character from the current read position.'''
        pos = self.linebuf.tell()
        self.dbg("rewind1 from", pos, msg)
        if pos > 0:
            self.linebuf.seek(pos-1, 0)


    def refillLineBuffer(self, withinQuote=False):
        '''Read input lines into the buffer used for parsing.
           The line-buffer (linebuf) will always represent one
           logical input (tcl) line, possibly constructed from
           several text lines with escaped continuations at the
           end. End of line represents end of expression in Tcl,
           as does semi-colon. Newlines and semicolons are allowed
           within quotes, so when a quoted string is being scanned
           more lines may need to be loaded from the source.
        '''

        # io.StringIO wrappers are used to represent each line so
        # that s.read(1) can be used uniformly on job scripts in
        # disk files or as in-memory string blocks. The wrappers
        # also avoid the problem of having to constantly check for
        # end-of-buffer when indexing if raw strings are used.
        # A single StringIO object is reused via truncate() and
        # write() of each new line.

        if not self.isAtLineBufferEnd():
            return True

        # set buffer back to empty.
        self.linebuf.seek(0, 0)
        self.linebuf.truncate(0)

        linechunk = ""

        while True:
            line = self.jobsrc.readline()
            if not line:
                # end of file
                return False

            self.linenum += 1
            line = line.strip()  # deemed ok losing whitespace ends in quotes
            self.dbg("next line:\n>>>> ", line)

            if not line:
                # skip empty lines
                continue

            if line[-1] == '\\':
                # continuation char, store chunk, read next line
                linechunk += line[:-1] + ' '
                continue

            # attach new line to last chunk, if any
            line = linechunk + line
            linechunk = ''

            if not withinQuote and line[0] == '#':
                # skip trivial case of lines that start with comments
                continue

            # line buffer now has one line of text to process
            self.linebuf.write(unicode(line))
            self.linebuf.seek(0, 0)
            break

        return True


    def tclListToPythonList(self, tcltxt, tmpio=None):
        '''Parse a tcl list like {a {b c} "d e f" g} into
           a python list like ["a", "b c", "d e f", "g"]
           (for later serialization into JSON).
        '''
        if tmpio:
            self.dbg("list tmpio is", type(tmpio))
            # caller has a temporary StringIO for reuse
            tmpio.seek(0, 0)
            tmpio.truncate(0)
            tmpio.write(tcltxt)
            tmpio.seek(0, 0)
            vsrc = tmpio
        else:
            vsrc = StringIO(unicode(tcltxt))

        vlist = []
        while True:
            item = self.findOneTclToken(altsrc=vsrc)
            if item == None:  # empty string '' is ok
                break
            else:
                vlist.append(item)

        return vlist


    def isAtLineBufferEnd(self, iobuf=None):
        '''Check if the current read position of the given StringIO
           buffer is at the end position, i.e. next read() would get ''.
        '''
        if not iobuf:
            iobuf = self.linebuf

        k = iobuf.tell()
        q = iobuf.seek(0,2)
        if k == q:
            # read pos is at the end
            return True
        else:
            # put the read position back where it was
            iobuf.seek(k, 0)
            return False

    def getchar(self, quoted=False, altbuf=None, skipSpace=False):
        '''Return one character from the script source.
           Skip comments and whitespace.

           Since Tcl allows string literals to contain newlines
           (as whitespace) this scan can't be purely line-based,
           and instead must resort to char-by-char to track nested
           Tcl strings - which occur a lot in Tractor/Alfred jobs.
           The underlying python io routines are likely using an
           internal cache already, but an app level one is created
           here to track line numbers for error messages, and to
           allow python built-in string methods to efficiently 
           handle other aspects which /are/ line-oriented in Tcl/Alf.
        '''

        if altbuf:
            # such as when creating a python list from a Tcl quoted list
            # (as an extension we allow comma as whitespace list delimiter)
            while True:
                c = altbuf.read(1)
                self.trace("getq" if quoted else "getc", str(c))
                if not c:
                    return ''
                if not quoted and skipSpace and (c.isspace() or c==','):
                    continue
                elif '\\' == c:
                    c += altbuf.read(1)
                    self.trace("get2", str(c))
                return c

        # otherwise it's the more complicated full job script scenario

        while True:
            # a single call to getchar may end up reading 
            # multiple no-op lines from the job

            c = self.linebuf.read(1)
            self.trace("getq" if quoted else "getc", str(c))

            if quoted and not c:
                # Reached end of line buffer, but if we're inside
                # a quoted multi-line string, refill another line,
                # and continue scanning.
                self.dbg("REFILL IN QUOTE", quoted)
                if self.refillLineBuffer(quoted):
                    # newline on current line was removed by strip()
                    # so return one of those, and let the caller call
                    # back again to get the first char of the new buffer.
                    return '\n'
                else:
                    return None   # got End Of File (EOF)

            if not quoted:
                if not c:
                    self.dbg("getch EOL1:", self.CTX())
                    return ''  # eol
                elif skipSpace and (c.isspace() or c==','):
                    # as an extension allow comma as list-delim whitespace
                    continue
                elif c == '#':
                    # comment, ends expr, skip to eol
                    self.dbg("getch COMMENT", self.CTX())
                    self.linebuf.seek(0, 2)
                    return ''
                elif c == ';':
                    # Tcl semi-colon is end of expr,
                    # but retain the buffer for next pass
                    self.dbg("getch eox")
                    return ''

            if '\\' == c:
                # advance and add escaped char like \"
                # incl backslash in quoted string values
                c = self.linebuf.read(1)
                self.trace("got2 \\"+c)
                if not c:
                    # Backlash at end of buffer. It's not a line-continuation
                    # since that would have been handled by refillLineBuffer.
                    c = '\n' if quoted else ''
                if quoted:
                    # note, returning 2 chars
                    c = "\\"+c

            return c


    def findOneTclToken(self, expectBlock=False, altsrc=None):
        '''Find a single (string) token using Tcl-like parsing rules.
           Several job-specific multi-expr blocks get special start/stop
           handling in this line-oriented job parser.

           If the "altsrc" is given, assume it is an alternative
           simple substring requiring further parsing e.g. a tcl list,
           not the more of the  mainline job script itself.
        '''

        # outside quotes, skip whitespace, find first non-space
        # (within this same line/expression)
        c1 = self.getchar(altbuf=altsrc, skipSpace=True)
        if not c1:
            return None  # eol/expr
        self.trace("f1%sstart %s" % ('x' if expectBlock else '', c1))

        if expectBlock:
            # Handle start of nested multi-expr block, send caller a
            # special "block begin" token, assume they'll switch context.
            #
            # Note: The old job handler just relied on Tcl to collect
            # the -subtasks and -cmds blocks as simple (multi-line)
            # quoted strings in braces. Then later those string-blocks
            # were recursively parsed in context. Here the blocks are
            # actively expected (in-line) in certain parameter contexts
            # and handled in-line by changing the "parsing context".
            # This approach creates a subtlety where block-begin is
            # effectively end-of-expression and remaining whitespace
            # in the active line buffer must be flushed.
            if c1 == '{':
                self.dbg("found block open")
                return "_BlockBegin_" # special parameter VALUE
            else:
                raise TrAlfParseError("expected start of nested sub-exprs, but got:", c1)

        value = ''
        qquote = None

        # collect the next "word"
        if c1 == '}':
            # reached end of a block
            self.dbg("got BLOCK END")
            return "_BlockEnd_"
        elif c1 == '"':
            # begin "evaluated" regular Tcl double-quoted string
            # \k escaped chars become single char k (typically only \")
            # "a\"b" is three chars
            # { has no special meaning, doesn't need to be balanced
            self.trace("begin dblq")
            qquote = '"' # the end quote to find
        elif c1 == '{':
            # begin "literal" regular Tcl brace-quoted string
            # " has no special meaning
            # \ is just a regular character
            # {a\"b} is four chars
            # Any internal { must have a matching }, as does the outer str.
            # Except {a\{b} and {a\}b} do not require balancing, as if they
            # were escaped, but length of those two examples is 4 chars(!?)
            self.trace("begin outbrace")
            qquote = '}' # the end quote to find
        else:
            value = c1  # first letter of token

        # qstack tracks beginning of " or { string, popped when ended
        # also tracks internal {} pairs when they need to be balanced
        qstack = [] if not qquote else [qquote]

        while True:
            cc = self.getchar(qquote, altbuf=altsrc)
            if not cc:
                # eol or eox or eof, return what we've collected
                break

            if qquote == cc:
                # found end of a quoted (sub)string
                # NOTE: valid for quoted string to be empty! "" or {}
                if cc == '}' and len(qstack) > 1:
                    # interior quote balanced  {say {hello, world} ok}
                    value += cc
                    qstack.pop()
                    qquote = qstack[-1]
                    self.trace("end brace, pop, stk=%s" % qstack)
                    continue
                else:
                    # outermost scope ended, string complete
                    self.trace("end %s str" % qquote)
                    qquote = None
                    qstack = []
                    break

            elif cc == '{' and '}' == qquote:
                # start new interior literal {} that needs to be balanced
                # {{hi there} "I'm a tcl" list} and string
                qquote = '}'
                qstack.append(qquote)
                self.trace("push new brace substr, stk=" % qstack)
                value += cc

            elif not qquote and cc == '}':
                self.rewind1("f1eot")
                break
            elif not qquote and (cc.isspace() or cc in ',;'):
                # Whitespace outside quotes marks end of token.
                # As an extension we allow comma as list delimiter.
                # Semi-colon is a Tcl expression delimiter, like newline
                # (when not in quotes). But need to call out "eol" without
                # actually incrementing line count.
                self.trace("f1eox: '%s'" % cc)
                break
            elif 2==len(cc) and cc[0]=='\\' and qquote != '}':
                # retain only the inbound escaped char in dbl-quoted str,
                # may be re-escape in json output
                # and handle weird \{ and \} inside {} cases
                # (otherwise retain both chars inside braces)
                self.trace("add escaped '%s'" % cc[1])
                value += cc[1]
            else:
                # otherwise it's just the next character in the string
                # (or retained \k inside {})
                value += cc

        if qquote:
            self.dbg("qstk:", qstack, "v:", value)
            raise TrAlfParseError("unterminated quoted string, line %d" % self.linenum)
        else:
            self.dbg("token '%s'" % value)
            return value


    def gatherNextParamPair(self, implicitKey=None):
        '''Collect a key-value pair for a Task or Command.
           These pairs are of the form:  -key_name value_string with
           only a couple exceptions determined by context. Values are
           strings when parsed, but will be converted to the type of
           the corresponding (default) item in the s_defaultParams table.
           Some key_names have values that are multi-item/line blocks.
           '''

        # Collect the -KEY-
        # capture the key word, like: -service
        # name only, not a fully general string token, no quotes etc
        #
        self.dbg("enter gatherParam")
        key = self.findOneTclToken()
        value = None

        if not key:
            # end of params for this task/cmd
            return (None, None)
        elif key == "_BlockEnd_":
            return (key, -1)
        elif len(key) > 1 and '-' == key[0]:
            key = key[1:] # skip hyphen
        elif implicitKey:
            # non-keyword allowed if standalone value is possible
            # e.g. Cmd argv or Task title
            self.dbg("using implicit key:", implicitKey)
            # so the token we DID gather is the VALUE for the implicit key
            value = key
            key = implicitKey
        else:
            raise TrAlfParseError("expected %s parameter name (-xxxx) but got '%s' on line %d" % (self.CTX(), str(key), self.linenum))

        pkeys = s_defaultParams[self.CTX()]
        if key not in pkeys:
            err = "unknown %s parameter '%s' - line %d" % (self.CTX(), key, self.linenum)
            if self.options.strict:
                raise TrAlfParseError(err)
            else:
                self.log("WARNING: " + err + " (ignored)")
                defaultValue = ''
                useValue = False
        else:
            defaultValue = pkeys[key]
            useValue = True

        vtype = type(defaultValue)

        # Some param keys are known to introduce LISTS of (simple) strings,
        # and some introduce BLOCKS of nested job expressions.
        # In the tcl parser the blocks were just long mulit-line strings,
        # and those blocks were eventually passed through the parser
        # recursively to handle sub objects. Instead, this implementation
        # will shift parsing "contexts" at the start of a block and process
        # the next expressions in-line immediately.
        hasBlock = key in ("subtasks", "cmds", "init", "cleanup", "postscript")

        # Collect the -VALUE-
        if value == None:
            value = self.findOneTclToken(hasBlock and useValue)
        if value == None:
            # note: /None/ indicates missing value token, but empty string ok
            err = "no value given for %s option '%s' on line %d" % (self.CTX(), key, self.linenum)
            if self.options.strict:
                raise TrAlfParseError(err)
            else:
                self.log("WARNING: " + err)
                return key, None  # skipped

        self.dbg("gatherNextParam got: k=<%s>  v=<%s>" % (str(key),str(value)))

        if not useValue:
            return key, None
        elif value == "_BlockBegin_":
            return key, value

        # The key name is now known to be valid.
        # Now confirm/convert string tokens to expected types.
        try:
            if vtype == int:
                value = int(value)

            elif vtype == float:
                value = float(value)

            elif vtype == list:
                # Recursively tokenize the string into a list.
                # This is not just python val.split() since the
                # string can contain Tcl-style string groups that
                # need to be retained as a single list element.
                # like argv of "grep -i {we hold these} decl.txt"

                self.dbg("reparse as list:", key, "from <%s>" % value)
                value = self.tclListToPythonList(value)

                if key == "retryrc":  
                    # special case of a list that is expected to be ints
                    value = [int(v) for v in value]

                self.dbg("     >", key, repr(value))

            # otherwise string is expected

            if key == "dirmaps":
                # This double-nested tcl string needs to be converted
                # into a python list of lists.
                value = self.reformatDirmaps(value.strip())

        except ValueError:
            raise TrAlfParseError("invalid value for '-%s' - requires %s, line %d" % (key, str(vtype), self.linenum))

        # Done finding one parameter key-value pair.
        # ... but only keep parameters that are different from the defaults.
        if value == defaultValue:
            value = None
            self.dbg("  skip default [%s]" % (key))
        else:
            self.dbg("         using '%s': %s" % (key, repr(value)))

        return key, value


    def addTaskParams(self, curTask):
        '''Loop over the input stream adding "-name value" pairs
           from the job script to the current Task's dict.
           If the name opens a sub-block, then stop here,
           change the parsing context, and let the caller's
           outer loop deal with the block context.
        '''

        self.dbg("enter addTaskP")
        # Compatibility issue, older job scripts allowed this:
        #   Task {my task title} -cmds {...}
        # where the Task title string VALUE is the next token
        # without a preceding '-title'. Some scripts /will/ 
        # provide the -title keyword, so we need to handle both
        # the explicit and implicit -title cases.
        taskImplicit = None if curTask.get('title') else "title"

        while True:
            self.dbg("addT loop ...")
            key, value = self.gatherNextParamPair(taskImplicit)
            self.dbg("   addT, key:", repr(key))
            if not key:
                # reached EOL, task parameters complete
                self.dbg("reached eol - emtpy key - after gather in addT")
                break
            elif not value:
                # skip, param has default value
                continue
            elif key == "_BlockEnd_":
                # End of parsing inside a subtask block.
                # Push that back for the top-level scanner.
                self.dbg("push-block-end in addTaskP")
                self.rewind1("taskblk")
                return curTask
            elif key == "subtasks":
                if value != "_BlockBegin_":
                    raise TrAlfParseError('no Task block for -subtasks, line %d' % self.linenum)
                self.dbg("taskStack PUSH - open subtask block in task", curTask['tid'])
                self.CTX("Task")
                self.taskStack.append(curTask) # push parent on the stack
                curTask = None
                break # new block temporarily shifts parsing to contents

            elif key == "init":
                # Job -init {Assign x y; ...}
                if value != "_BlockBegin_":
                    raise TrAlfParseError('no Assign block for -init, line %d' % self.linenum)
                self.dbg("start <<init>> block")
                self.CTX("Assign")
                break  # skip out to process (ignore) Assign statements

            elif key in ("cmds", "cleanup", "postscript"):
                if value != "_BlockBegin_":
                    raise TrAlfParseError('no Cmd block for -%s, line %d' % (key, self.linenum))

                # Parsing resumes with the new block,
                # allowing only RemoteCmd/Cmd,
                # and populating the commands list of the current task.
                #
                # Note that most inbound alfscript parameter names just end
                # up directly as keys in the outbound JSON dict, however the 
                # inbound alfscript -cmds list is renamed "commands" in JSON.
                # The "key" variable here could be set to "commands" for 
                # completeness, but it isn't actually referenced past this
                # point, the Cmd operator processing just populates the
                # outbound "commands" dict entry directly.

                self.cmdScope = {"cmds": 'C', "cleanup": 'D', "postscript": 'P'}[key]
                self.CTX("Cmd")
                break

            else:
                # We now have a complete key-value pair, and the
                # key is a valid item in the canonical Task dict,
                # and the value is different than the default.

                if key in ("whendone", "whenerror"):
                    # this old-school key-value gets converted to a Cmd,
                    # and don't add them to the task dict as k,v
                    self.handleOldWhenCmd(key, value.strip(), curTask)
                    continue
                elif key == "tags":
                    value = self.reformatLimitTags(value)
                elif key == 'title':
                    value = value.strip()

                # for job params, retain values that came from cmdline args,
                # those are treated as overrides to anything in the file
                if self.chkNoJobOverride(curTask, key):
                    # no override, add this key-value pair!
                    curTask[key] = value
                    self.dbg("  Adding", key, '=', value, "to task", curTask['tid'])

                if key == taskImplicit:
                    # found a value for the implicit key, so return
                    # to requiring proper key-value pairs only
                    taskImplicit = None

        # Reached end of line or beginning of new block
        if curTask and value != "_BlockBegin_":
            # Not opening a sub block, so this task is complete.
            self.dbg("END of param scan, tid", curTask['tid'])
            self.chkAttachTaskToParent(curTask)

            # further jobfile line parsing cannot append to that task anymore
            curTask = None

        return curTask

    def chkNoJobOverride(self, jdict, jkey):
        # Check whether the job received a value for this key
        # from command-line options that should be retained.
        # returns:
        # False: don't use new value from file, override was given
        # True: ok to use, no override
        return "Job" != self.CTX() or jkey not in jdict or \
            s_defaultParams["Job"][jkey] == jdict[jkey]

    def chkAttachTaskToParent(self, aTask):
        # This function may be called twice on a given task:
        # - once when the end of task params are definitively found
        # - maybe again if a task block is closed with the last task 
        #   not yet 'terminated' by definitive eol
        if not aTask:
            return
        tid = aTask.get('tid', None)
        self.dbg("chkAtt t:", tid)
        if tid and tid < 0:
            # Negative tid value indicates that this task
            # has not yet been attached to the job graph.
            # Now that all attributes are present it can
            # be attached. Negate the tid (to positive)
            # to indicate that it's already been attached.
            tid = -tid
            aTask['tid'] = tid

            self.updateSlotCounts(aTask)

            # shuffle into "2.0" format if reqd
            if self.options.jsonAPI == "2.0":
                aTask = {
                    "#": 'T'+str(tid),
                    "data": aTask,
                    "children": aTask.pop('subtasks')
                }

            pt = self.taskStack[-1] # parent on stack
            self.dbg("ADDING task", tid, "to task", pt['tid'])
            pt["subtasks"].append(aTask)
            self.dbg("      ... now nt =", len(pt["subtasks"]))


