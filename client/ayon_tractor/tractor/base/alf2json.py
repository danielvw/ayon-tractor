# Generate Tractor JSON job definitions from
# alfred-style Tcl-based job scripts.
#
# dml, 09/2023
#
#
# The original Tractor/Alfred jobs were written to be parsed by a
# "readily available" Tcl (tclsh) interpreter. As Python became
# more standard for full app development, the Tractor job submission
# scheme required both interpreters. To simplify product deployment,
# Tractor (2.0) shipped with a full bundled python distribution (2.7.2)
# that included an embedded Tcl interpreter (c++ module) callable from
# python scripts.
#
# This script is a new pure-python "alf2json" module that addresses
# the problem of providing a job submission/parsing solution that
# can be run in stock Python distributions without the need to build
# and distribute the compiled Tcl module for each platform variant.
#
# This python implementation essentially treats Tractor jobs as
# "structured data" only, not as full tclsh scripts (for example, no
# inline tcl execution or even variable substitution are allowed).
# The code is really in two parts:
#  - A simplistic tokenizer, aware of a limited Tcl-like grammar.
#  - Job-specific handling of the tokenizer results to produce a
#    JSON job representation. It includes logic to handle various
#    anachronistic job script details for backward compatibility.
#
# This is a line-oriented parser, handling nested subtask and cmd
# blocks with a simple depth tracker and NO RECURSION. It builds
# stock python dicts and lists directly without requiring any
# intermediate python classes for Job, Task, Cmd, etc. The python
# dict/list hierarchy is serialized to JSON.
#
# The approach is to read the job file one line at a time.
# Actionable lines will have a Tcl-like expression form:
#
#   jobElement -optionName valueString [more opt-value pairs...]
#
# In the old Tcl implementation, each job element was implemented
# as a standard Tcl operator: Job, Task, RemoteCmd, Cmd, Assign.
# Each operator handled its arguments, delivered the Tcl interpreter,
# in its own "custom" fashion (in the tcl code for the operator).
#
# In this implementation we're treating the script as just
# structured data instead, so the given job element keywords
# dictate the processing rules applied to subsequent tokens,
# however most are indeed key-value pairs and are just placed
# into each element's associated python dict directly.
#
# There is a longstanding Task and Cmd syntax anachronism where they
# both have one required parameter that is not given as a key-value
# pair, just the valueString is given, with the optionName implied.
#
# Recall that in Tcl, double-quotes and curly-braces are both
# used as string delimiters, and that literal strings can contain
# newlines. Some std Tcl operators like [lindex] examine strings
# for nested string subsyntax and create Tcl lists from them.
# Depending on context in job scripts, curly-brace strings are
# treated as simple strings, or sometimes lists, and also to
# denote multi-line blocks of subtasks or commands. Those blocks
# were recursively parsed in Tcl for more Task and Cmd operator
# statements. Here we handle those particular multi-line blocks
# line by line and simply track nested scope depth as we go.
#
# These subtask and cmd blocks (specifically) can be handled
# in a line-by-line fashion without recursion because alfred job
# scripts always present the task hierarchy tree in a strictly
# depth-first nesting order. When a block is found, state from
# the current Task is pushed on a simple stack and items from
# inside the block are inserted into the topmost task.
# Updates return to the prior task dict when the block ends.
#
# == Other notes ==
#
# Preview and chaser commands...
# See the trSiteOpenPreviewLink() comments in the site modifiable
# trSiteDashboardFunctions.js config file. Format like
#    Task -preview { cmdline }  or -chaser { cmdline }
# These strings are messages to the Tractor javascript code running
# in the dashboard (browser). The job database expects these directive
# strings to be converted to json "argv" style tokenized lists, though
# they can be interpreted differently by the site plug-in.
#


