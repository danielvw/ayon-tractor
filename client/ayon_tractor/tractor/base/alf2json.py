## ===== ##


def ParseAlfJob(options, jobfile, jobtext=None, openedfile=None):
    '''Read a Tractor "alfred-format" job script
       and convert it to a JSON dict hierarchy
       as expected by the Tractor2 job database.
    '''

    try:
        if not getattr(options, 'jobfile', ''):
            options.jobfile = jobfile  # a label in this case

        alfParser = AlfJobParser(options)

        if jobtext:
            # Received an in-memory job as a text block.
            jtxt = StringIO(unicode(jobtext))
            return alfParser.xlateAlfToJSON(jtxt)

        elif openedfile:
            return alfParser.xlateAlfToJSON(openedfile)

        else:
            # Read the job file from disk.
            # Open the file within an auto-close context.
            with open(jobfile, "r") as jf:
                return alfParser.xlateAlfToJSON(jf)

    except Exception as err:
        msg = str(err)
        if getattr(options, "IsModuleTest", False):
            if options.loglevel >= 5:
                import traceback
                msg += "\n" + traceback.format_exc()

            print("Error - ParseAlfJob:", msg, file=sys.stderr)
            return None
        else:
            raise err

## ===== ##
def ParseAlfJobAsString(jobtext, loglevel=1):
    '''Simplified entry point for job authoring API to use.
       Parse an in-memory alf job text buffer.
    '''
    if not jobtext:
        return ''
    else:
        class MinimalOptions(object):
            pass
        opts = MinimalOptions()
        opts.loglevel = loglevel

        return AlfJobParser(opts).xlateAlfToJSON(
                    StringIO(unicode(jobtext))
                )

