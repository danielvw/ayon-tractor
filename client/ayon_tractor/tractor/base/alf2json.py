if __name__ == "__main__":
    '''The alf2json module is imported into either tractor-spool or
       dbJobStaging inside the database.  This main() is used only
       for standalone testing.
    '''

    argc = len(sys.argv)
    jobfile = None

    class OptionHolder(object):
        pass
    opts = OptionHolder()
    opts.IsModuleTest = True
    opts.jobfile = None
    opts.jsonAPI = "2.0"
    opts.loglevel = 1
    opts.priority = 1.0
    opts.strict = False

    i = 0
    while  i < argc-1:
        i += 1
        opt = sys.argv[i]
        if opt == "--debug":
            opts.loglevel = 5
        elif opt == "--trace":
            opts.loglevel = 11 
        elif opt == "--title":
            i += 1
            opts.jtitle = sys.argv[i]
        elif opt == "--strict":
            opts.strict = True
        elif opt == "--paused":
            opts.paused = True
        elif opt == "--pretty":
            opts.jsonformat = (2, (', ', ': '))
        elif opt == "--expand":
            opts.expandctx = "1.234.5.6.0.0"
        elif opt == "--3.0":
            opts.jobspec = "3.0"
        elif opt[0] == "-":
            print("unknown alf2json option:", opt, file=sys.stderr)
            break
        elif i == argc - 1:
            jobfile = opt
        else:
            print("only one job filename allowed, found:", sys.argv[i:], file=sys.stderr)
            break

    if not jobfile:
        usage()

    if not os.path.exists(jobfile):
        print("can't access job file: '%s'" % jobfile, file=sys.stderr)
        sys.exit(2)

    jobJSON = ParseAlfJob(opts, jobfile, None)
    if not jobJSON:
        sys.exit(113)

    sys.stdout.write(jobJSON)
    sys.stdout.write('\n')
    sys.stdout.flush()

